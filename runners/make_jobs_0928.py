#!/usr/bin/env python
"""0928 발주서 — **실외에서 물리 스위치를 처음으로 흔든다.**

■ 어디서 나왔나 (⛔지어낸 물음이 아니다 — 재고를 세었다)
  2026-09-12 재고(spp 4e9 · 깊이 2 · 15 m · matrice4e · 자세 8,192 완결, 팔 × 앙각):

      장면        확산만  +굴절  +굴절+모서리  +반사  전부
      빈 하늘       6/6    4/6     6/6       6/6   6/6
      우리 실외     6/6    3/6     6/6       6/6   6/6
      거리 협곡     6/6    3/6     2/6       5/6   2/6
      지면만       6/6    0/6     2/6       0/6   0/6
      건물만       5/6    0/6     2/6       0/6   0/6

  ⇒ **덱이 보여 주는 장면(거리 협곡)에서 네 팔이 −30·−60 두 각도에만 서 있고**,
    장면을 조각낸 판(지면만·건물만)에서는 세 팔이 **한 칸도 없다.**

■ 왜 사나 — 지금 우리가 못 하는 말
  ① 0910 덱 9 쪽이 스스로 열어 둔 문제가 있다:
     「⚠회절을 켠 두 팔은 다섯 칸에서 필터 뒤 값이 빈 하늘보다 **높다** — 필터가 없던
       구조를 만들었는지 **안 갈랐다**. 그 팔에는 아직 안 쓴다.」
     그 판정을 하려면 회절 팔이 **여러 앙각에** 서야 하는데 지금은 −30·−60 뿐이다.
  ② 실외에서 얻은 수(갈아낀 자세 96·339)는 **확산만 켠 한 팔**의 것이다. 굴절·모서리·
     반사를 켜면 그 수가 어떻게 되는지 **한 번도 안 봤다.**
  ③ 「지면이 하나 건물이 하나」를 가르는 축(지면만·건물만)은 확산만 팔로만 있어,
     **장면 축과 물리 축을 교차시킬 수가 없다.**

■ 무엇을 사나 — 15 m · 깊이 2 · spp 4e9 · matrice4e · 자세 8,192 · 2 조각
  ⛔el 0 은 안 산다 — 그 앙각의 빈 하늘 기록은 인용이 막혀 있다(GATES_0902).
  A 지면만·건물만 +굴절+모서리 {−15,−45,−75} 씩 · 건물만 확산만 {−75}   ← 싸고 비어 있다
  B 거리 협곡    +굴절+모서리 {−15,−45}                              ← 덱의 ⚠ 를 두 점 더
  ⛔협곡의 «전부» 팔(R1D1E1F1)은 안 산다 — 한 샤드 821 분이라 6 줄이면 82 일꾼시간이다.
    같은 물음을 지면만·건물만에서 190·276 분에 살 수 있다. 협곡은 그 뒤에 본다.
  ⛔빈 하늘 짝은 이미 있다 — +굴절+모서리 팔은 −15·−45·−75 가 다 차 있다(4·3·1 칸).

■ ⛔이 묶음이 답하지 않는 것
  · ⛔「어느 팔이 맞는가」를 답하지 않는다. 다섯 팔은 전부 근사이고, 어느 것이 현실인지는
    실기 계측이 정한다 — **실기 계측 대조는 0 건이고 이 판으로도 안 생긴다.**
  · ⛔팔 사이의 **절대 레벨을 견주지 않는다**(집 규약). 읽는 것은 «같은 팔 안에서
    장면이 얹은 몫» 과 «사건 빈도» 다.
  · ⛔지면만·건물만은 **우리가 만든 장면을 조각낸 것**이다. 거리 협곡(솔버가 주는 장면)의
    지면·건물과 같지 않다 — 두 장면을 가로질러 더하지 않는다.
  · ⛔드론 고도가 장면마다 다르다(우리 장면 20 m · 솔버 장면 25 m). 장면끼리 견줄 때
    이것을 먼저 적는다.
  · ⛔상한이 결과를 정하면 그 축은 접는다 — n_trunc 를 먼저 본다.

■ 죽는조건
  · 회절을 켠 팔에서도 필터 뒤 값이 빈 하늘 아래로 내려오면, 9 쪽의 ⚠는 **−30·−60 에
    한정된 것**이었다고 적고 그 팔에도 필터를 쓴다.
  · 여러 앙각에서 계속 위로 뜨면 그것은 **필터가 만든 구조**이므로, 회절 팔에는 이 필터를
    쓰지 않는다고 못 박고 그 이유를 문서에 남긴다.
  · 지면만·건물만에서 사건 수가 크게 갈리면 96·339 를 「장면이 얹은 것」으로 말할 때
    **어느 조각이 얹었는지**까지 적을 수 있다. 안 갈리면 그 말은 못 한다.

쓰는 법:
    /workspace/.venvs/py312/bin/python runners/make_jobs_0928.py --summary
    /workspace/.venvs/py312/bin/python runners/make_jobs_0928.py > runners/jobs_0928.txt
  ⭐발주 전 반드시:
    grep -vE "^\\s*(#|$)" runners/jobs_0928.txt \\
      | xargs -d"\\n" -P 4 -I{} runners/filter_jobs.sh {} | cut -d"|" -f1 | sort | uniq -c
"""
from __future__ import annotations
import sys

SPP, NSH = 4_000_000_000, 2
BASE = f"--engine sionna --spp {SPP} --n-poses 8192 --max-depth 2 --range-m 15"
CANYON = "sionna:simple_street_canyon"

#: (꼬리표, --env 값, 팔, 앙각들, 한 샤드 어림 분)
#: ⛔⛔한 샤드의 값은 **장면만이 아니라 장면 × 팔**로 정해진다 (2026-09-12 실측).
#  회절·모서리를 켜면 같은 장면에서 3~4 배가 된다:
#      깊이 2 · 한 샤드 중앙 분   확산만  +굴절  +굴절+모서리  +반사   전부
#        빈 하늘                  38     71      67        43     72
#        우리 실외               121    370     411       100    413
#        지면만                   80      —     190         —      —
#        건물만                   95      —     276         —      —
#        거리 협곡               194    569     515       170    821
#  ⇒ **켠 팔은 싼 장면에서 산다.** 협곡에서 같은 것을 사면 3 배를 낸다.
#    (첫 판에서 장면 하나에 한 값을 썼다가 93 일꾼시간으로 잡았는데 실제는 226 이었다.)
BLOCKS = [
    ("A 지면만 — 장면 조각 × 물리 축을 처음 교차시킨다", "outdoor01_ground", [
        ("R0D1E1F1", (-15, -45, -75)),
    ], 190),
    ("A 건물만 — 같은 교차 · 확산만 팔의 −75 도 함께", "outdoor01_bldg", [
        ("R0D1E1F1", (-15, -45, -75)),
        ("R0D0E0F1", (-75,)),
    ], 276),
    ("B 거리 협곡 — 덱 9 쪽이 열어 둔 ⚠를 두 앙각 더 본다", CANYON, [
        ("R0D1E1F1", (-15, -45)),
    ], 515),
]

OUT: list[str] = []
OUT.append("# ══ 0928 큐 — 실외에서 물리 스위치를 처음으로 흔든다 ══")
OUT.append("#  ⛔여기 적힌 것은 «물음» 이지 «답» 이 아니다.")
OUT.append("#  ⛔「어느 팔이 맞는가」를 답하지 않는다 — 다섯 팔은 전부 근사다.")
OUT.append("#  ⛔팔 사이의 절대 레벨을 견주지 않는다. 같은 팔 안에서 장면이 얹은 몫만 읽는다.")
OUT.append("#  ⛔지면만·건물만은 우리 장면을 조각낸 것이다 — 솔버가 주는 협곡과 같지 않다.")
OUT.append("#  ⛔드론 고도가 장면마다 다르다(우리 20 m · 솔버 25 m).")
OUT.append("#  ⛔el 0 은 안 산다(GATES_0902 — 그 앙각의 빈 하늘 기록은 인용이 막혀 있다).")
OUT.append("#  ⛔실기 계측 대조는 0 건이고 이 판으로도 안 생긴다.")
OUT.append("")
tot_lines = tot_min = 0
for title, env, arms, mins in BLOCKS:
    n0 = len(OUT)
    OUT.append(f"# ── {title}")
    for arm, els in arms:
        for el in els:
            for k in range(NSH):
                e = f" --env {env}" if env else ""
                OUT.append(f"{BASE} --sw {arm} --els={el}{e} --shard {k} --nshards {NSH}")
    n = sum(1 for x in OUT[n0:] if x and not x.startswith("#"))
    tot_lines += n; tot_min += n * mins
    OUT.append(f"#   위 {n} 줄 · 한 샤드 어림 {mins} 분 ⇒ {n*mins/60:.0f} 일꾼시간")
    OUT.append("")

if "--summary" in sys.argv:
    print(f"발주 줄 {tot_lines} · 어림 {tot_min/60:.0f} 일꾼시간 "
          f"(일꾼 9 이면 약 {tot_min/60/9:.0f} 시간)")
    for title, env, arms, mins in BLOCKS:
        n = sum(len(e) for _, e in arms) * NSH
        print(f"   {title[:46]:48s} {n:3d} 줄 · {n*mins/60:5.0f} 일꾼시간")
    print("   ⛔값은 장면 × 팔의 실측 중앙이다 — 팔을 켜면 3~4 배가 된다.")
else:
    print("\n".join(OUT))
