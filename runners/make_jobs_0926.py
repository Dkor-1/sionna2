#!/usr/bin/env python
"""0926 발주서 — 0925 의 «격자 민감도 사다리» 를 **나머지 앙각**에 건다.

■ 어디서 나왔나 (⛔지어낸 물음이 아니다)
  협곡에는 4e9 기준선이 여섯 앙각(+0 · −15 · −30 · −45 · −60 · −75)에 다 있다.
  그런데 예산을 흔들어 본 곳은 **−30 과 −60 둘뿐**이고, 거기서 이렇게 나왔다
  (`outputs/read_canyonnull_0910.json`, 사건 규칙 DEV=0.5):
      el −30 : 기준 96 · 3.8e9 → 0.6031 · 4.2e9 → 0.6250
      el −60 : 기준 128 · 3.8e9 → 0.7315 · 4.2e9 → 0.7740
  두 앙각의 값이 **겹치지 않는다**(0.60~0.63 대 0.73~0.77). 2026-09-11 에 이 둘을 한 «띠» 로
  합쳐 판정 문턱으로 쓰던 문장을 내렸다 — 서로 다른 조건의 점이기 때문이다.

  ⇒ 그러면 곧장 따라오는 물음: **민감도가 앙각을 타나?**
    −30 과 −60 만으로는 점이 둘이라 말할 수 없다. 나머지 세 앙각에 **같은 사다리**를 걸면
    「앙각이 오를수록/내릴수록 갈린다」를 한 축 안에서 볼 수 있다.

■ 무엇을 사나 — 협곡 · matrice4e · 15 m · R0D0E0F1 · 깊이 2 · 자세 8,192
  앙각 **−15 · −45 · −75** (각각 지금은 4e9 한 점뿐이다)
  예산 **3.6e9 · 3.8e9 · 3.9e9 · 4.1e9 · 4.2e9 · 4.29e9** (6 점) × 샤드 2 × (장면·빈 하늘)
  = 3 × 6 × 2 = **72 줄** (장면 36 + 빈 하늘 36)

  ⛔**el +0 은 사지 않는다** — 그 앙각의 빈 하늘 기록은 「같은 경로가 여러 줄로 적힌」 판이라
    집 규약이 인용을 막고 있다(GATES_0902 · 리포트 12 의 el 0° 열 철회).
  ⛔**축이 위로 비대칭이다** — Sionna 표본기의 `wavefront_size` 가 uint32 라 광선 예산의
    천장이 4,294,967,295 다(`elevation_sweep_md.py:567`). 위쪽 끝은 4.29e9 가 한계이고
    −10 % 는 되지만 +10 % 는 못 산다. 결과에 이 비대칭을 함께 적는다.

■ ⛔이 묶음이 답하지 않는 것
  · ⛔**«널» 이 아니다.** 초기 광선은 씨앗 없는 결정적 피보나치 격자다
    (sionna/rt/utils/ray_tracing.py:24-30). 점이 몇 개가 되어도 신뢰구간이 되지 않는다.
  · ⛔광선 수를 바꾸면 경로 수와 경로당 가중치가 함께 움직인다(field_calculator.py:221).
  · ⛔앙각이 바뀌면 **날개끝 주파수도 cos(el) 로 바뀐다** — 사건 규칙은 레벨 문턱을 안 쓰지만,
    「앙각을 탄다」를 곧장 «기하 탓» 으로 읽지 마라. 이 축으로는 둘을 못 가른다.
  · ⛔실기 계측 대조는 0 건이고 이 판으로도 안 생긴다.

■ 죽는조건
  · 다섯 앙각의 겹침이 **앙각에 단조**면 「민감도는 시선 각도를 탄다」가 서고, 그때 비로소
    앙각별로 폭을 적을 수 있다(⛔여전히 신뢰구간이라 부르지 않는다).
  · 앙각과 무관하게 흩어지면 이 잣대는 조건별로 다르게 움직인다는 뜻이다 ⇒
    **자카드를 조건 사이 비교의 잣대로 쓰는 것을 그만둔다.**
  · 어느 칸이든 경로 수가 상한(2,000,000)에 붙으면 그 칸은 접는다(집 규약).

쓰는 법:
    /workspace/.venvs/py312/bin/python runners/make_jobs_0926.py --summary
    /workspace/.venvs/py312/bin/python runners/make_jobs_0926.py > runners/jobs_0926.txt
  ⭐발주 전 반드시:
    grep -vE "^\\s*(#|$)" runners/jobs_0926.txt \\
      | xargs -d"\\n" -P 4 -I{} runners/filter_jobs.sh {} | cut -d"|" -f1 | sort | uniq -c
"""
from __future__ import annotations
import sys

ARM, ENV, NSH = "R0D0E0F1", "sionna:simple_street_canyon", 2
ELS = (-15, -45, -75)          # ⛔+0 은 규약이 막는다 · −30·−60 은 0925 가 산다
SPPS = [(3_600_000_000, "−10 %"), (3_800_000_000, "−5 %"), (3_900_000_000, "−2.5 %"),
        (4_100_000_000, "+2.5 %"), (4_200_000_000, "+5 %"),
        (4_290_000_000, "+7.25 % · uint32 천장 바로 아래")]
BASE = "--engine sionna --n-poses 8192 --max-depth 2 --range-m 15"

OUT: list = []
OUT.append("# ══ 0926 큐 — 격자 민감도 사다리를 나머지 앙각에 건다 ══")
OUT.append("#  ⛔여기 적힌 것은 «물음» 이지 «답» 이 아니다.")
OUT.append("#  ⛔«널» 이 아니다 — 씨앗 없는 결정적 격자다. 점이 늘어도 신뢰구간이 아니다.")
OUT.append("#  ⛔el +0 은 사지 않는다 — 그 앙각의 빈 하늘 기록은 인용이 막혀 있다(GATES_0902).")
OUT.append("#  ⛔축이 위로 비대칭이다 — uint32 천장 4,294,967,295. 위쪽 끝은 4.29e9 다.")
OUT.append("#  ⛔앙각이 바뀌면 날개끝 주파수도 cos(el) 로 바뀐다 — 「앙각을 탄다」를 기하 탓으로 곧장 읽지 마라.")
OUT.append("#  ⛔실기 계측 대조는 0 건이고 이 판으로도 안 생긴다.")
OUT.append("#  ⚠협곡 한 샤드가 실측 중앙 238 분이다 — 72 줄이면 어림 143 일꾼시간.")
OUT.append("")
for el in ELS:
    OUT.append(f"# ── 앙각 {el:+d} — 지금은 4e9 한 점뿐이다")
    for spp, lbl in SPPS:
        OUT.append(f"#   예산 {spp:,} ({lbl})")
        for k in range(NSH):
            #: ⭐⭐**장면과 빈 하늘을 같은 예산으로 짝지어 산다.**
            #  ⛔read_canyonnull_0910.stem() 이 둘을 같은 예산으로 묶는다 — 장면만 사면
            #    그 예산 점은 **한 칸도 못 읽는다**(2026-09-11 실측: 새 점의 빈 하늘 0 장).
            OUT.append(f"{BASE} --spp {spp} --sw {ARM} --els={el} --env {ENV} "
                       f"--shard {k} --nshards {NSH}")
            OUT.append(f"{BASE} --spp {spp} --sw {ARM} --els={el} "
                       f"--shard {k} --nshards {NSH}")
    OUT.append("")

if "--summary" in sys.argv:
    n = sum(1 for x in OUT if x and not x.startswith("#"))
    print(f"발주 줄 {n} · 앙각 {len(ELS)} × 예산 {len(SPPS)} × 샤드 {NSH}")
    print("어림 — 협곡 한 샤드 238 분 ⇒ 36 × 4.0 h ≈ 143 일꾼시간")
else:
    print("\n".join(OUT))
