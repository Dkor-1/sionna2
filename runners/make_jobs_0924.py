#!/usr/bin/env python
"""0924 발주서 — 2026-09-10 의 동체 사다리 판독이 **직접 연** 칸만 산다.

■ 어디서 나왔나 (⛔지어낸 물음이 아니다)
  09-10 에 `benchmark/read_bodyladder_0910.py` 가 **이미 구워 둔** bs 샤드 다섯을 읽었다
  (원장 `outputs/read_bodyladder_0910.json`). 앙각 −60 · 우리 씬 땅만 · 팔 R0D0E0F1 ·
  4e9 · 깊이 2 · 자세 8,192 · 기준선 사건 82 개:

      동체 ×0.4  남음 80      ×0.5  80      ×0.6  80      ×0.8  80
      동체 ×1    남음 82(기준선)               ⭐×2   남음 **64**
      (참고선) 격자 3.8e9 남음 80 · 격자 4.2e9 남음 80

  ⇒ 줄이는 쪽은 2.5 배를 훑어도 **전부 80** 이라 격자를 갈았을 때와 구별되지 않는다.
    바뀌는 것은 ×2 한 칸뿐이다. **그런데 ×1 과 ×2 사이를 한 번도 안 샀다.**

■ ⛔⛔이 발주서를 읽는 사람이 오해하지 않도록
  · 여기 적힌 것은 «물음» 이지 «답» 이 아니다. 묶음 이름은 무엇을 사는지다.
  · ⛔「우리 커널이 맞고 솔버가 틀렸다」를 겨누는 줄은 없다. 둘 다 근사다.
  · ⛔실기 계측 대조는 0 건이고 이 판으로도 안 생긴다.

■ ⚠이 판 전체에 걸리는 한계
  ① ⛔`bs` 는 **모형 축**이지 실기 형상이 아니다 — 비구조 산란면만 키우고 팔·모터·기어·
     다리와 허브·프롭은 고정한다(src/articulated_fast.py:126·:145). 줄이면 동체와 팔
     사이에 **틈이 생긴다**. 발표에 그렇게 적는다.
  ② ⛔⛔**동체 배율과 경로 수가 함께 움직인다** — ×2 에서 경로 수 중앙이 2,705 → 6,841 이다.
     어느 쪽이 목록을 옮겼는지 이 축으로는 **못 가른다**. ⚠다만 경로 수만으로도 못 읽는다:
     ×0.4→×1 도 1,602 → 2,705(1.7 배)인데 목록은 2 개만 바뀐다.
  ③ ⛔C 묶음의 광선 예산은 «널» 이 아니다 — 초기 광선은 씨앗 없는 결정적 피보나치 격자다
     (sionna/rt/utils/ray_tracing.py:24-30). 같은 설정 되풀이는 자카드 1.000 이라 확률적
     널이 아예 없다. **«격자를 갈았을 때의 민감도»** 로만 부른다. 신뢰구간이 아니다.
  ④ ⛔예산을 바꾸면 경로 수와 **경로당 가중치**가 함께 움직인다(4π/samples_per_src,
     field_calculator.py:221). 단일 변수가 아니다.
  ⑤ ⛔D = E_장면 − E_빈하늘 은 «환경 산란» 이 아니다 — 차폐·드론 경로 변화·후보 탐색
     차이가 함께 들어간다. 「장면이 얹은 몫」으로만 부른다.
  ⑥ ⛔상한과 중복제거 해시 통 수가 묶여 있다(spec_counter_size = max(상한, 1e6)).

■ 상시 규약 — ⛔확산(F 비트) 항상 켬 · ⛔프롭 단독 없음 · ⛔뮌헨 없음 · ⛔챔버 없음
  ⛔지면 거칠기 축은 접은 채로 둔다.

쓰는 법:
    /workspace/.venvs/py312/bin/python runners/make_jobs_0924.py --summary
    /workspace/.venvs/py312/bin/python runners/make_jobs_0924.py > runners/jobs_0924.txt
"""
import sys

BASE = "--engine sionna --spp {spp} --n-poses 8192 --max-depth 2 --range-m 15 --sw R0D0E0F1"
ENV = "outdoor01_ground"
NSH = 2
OUT: list = []
GROUPS: list = []
_SEEN: set = set()
#: 어림 — 빈 하늘 15 m 44 분 · 우리 씬 땅만 136 분 (0923 발주서의 어림을 그대로 쓴다)
COST = {"free": 44, "scene": 136}
_cost = 0


def sec(title, *notes):
    GROUPS.append((title, len(OUT)))
    OUT.append("")
    OUT.append(f"# ══ {title} ══")
    for s in notes:
        OUT.append(f"#   {s}")


def job(*, el, spp=4_000_000_000, bs=None, scene=True, free=True):
    global _cost
    tail = f" --body-scale {bs:g}" if bs is not None else ""
    for want, e in ((scene, f" --env {ENV}"), (free, "")):
        if not want:
            continue
        for k in range(NSH):
            line = (BASE.format(spp=spp) + f" --els={el:g}{e}{tail}"
                    f" --shard {k} --nshards {NSH}")
            if line in _SEEN:
                OUT.append(f"#   ⤷ 건너뜀(이미 위에 있다): {line}")
                continue
            _SEEN.add(line)
            OUT.append(line)
            _cost += COST["scene" if e else "free"]


OUT.append("# ══ 0924 큐 — 09-10 동체 사다리 판독이 연 칸 ══")
OUT.append("#  ⛔여기 적힌 것은 «물음» 이지 «답» 이 아니다.")
OUT.append("#  ⛔bs 는 모형 축이다 — 비구조 산란면만 키운다. 실기 형상이 아니다.")
OUT.append("#  ⛔동체 배율과 경로 수가 함께 움직인다 — 어느 쪽이 목록을 옮겼는지 못 가른다.")
OUT.append("#  ⛔C 의 광선 예산은 «널» 이 아니다 — 씨앗 없는 결정적 격자다.")
OUT.append("#  ⛔실기 계측 대조는 0 건이고 이 판으로도 안 생긴다.")

sec("A ×1 과 ×2 사이 — 18 개가 갈리는 것이 계단인가 비탈인가 (앙각 −60)",
    "물음  줄이는 쪽은 ×0.4 까지 전부 80 인데 ×2 만 64 다. 그 사이를 한 번도 안 샀다.",
    "죽는조건  ×1.2·×1.5 가 80~82 면 ×2 는 **계단**이고 어딘가에 문턱이 있다.",
    "        80 → 74 → 68 → 64 처럼 매끄러우면 **비탈**이고 «문턱» 이라는 말을 접는다.",
    "        ×3 이 ×2 보다 더 안 내려가면 ×2 가 바닥이라는 관찰이 선다.",
    "⛔안답함  ⛔«왜» 에는 답하지 않는다 — 몇 개가 살아남나까지다.",
    "⛔안답함  ⛔경로 수가 함께 움직이는 것은 이 축으로 **안 갈린다**(한계 ②).")
for bs in (1.2, 1.5, 3.0):
    job(el=-60, bs=bs)

sec("B 같은 사다리를 앙각 −30 에서도 (씬 쪽만 산다 — 빈 하늘은 이미 있다)",
    "물음  「줄이는 쪽은 목록을 안 옮긴다」가 앙각 −60 한 자리의 이야기인가.",
    "죽는조건  −30 에서도 ×0.4~×0.8 이 서로 붙으면 앙각을 건너 같은 관찰이고,",
    "        흩어지면 «앙각 −60 에서만» 으로 좁혀 적는다.",
    "⚠빈 하늘 짝 bs0.4·0.6·0.8 은 el−30 에 **이미 있다** — 씬 쪽 여섯 줄만 산다.",
    "⚠×2 는 el−30 에 양쪽 다 없다 — 둘 다 산다.",
    "⛔안답함  ⛔앙각 0 은 이 묶음에 없다 — 거기는 지면 자체가 +53 dB 를 얹는 다른 이야기다.")
for bs in (0.4, 0.6, 0.8):
    job(el=-30, bs=bs, free=False)
job(el=-30, bs=2.0)

sec("C 참고선을 두 점에서 네 점으로 (앙각 −60)",
    "물음  «격자를 갈았을 때의 흔들림» 을 3.8e9·4.2e9 **두 점**으로만 재고 있다.",
    "      사다리의 칸을 그 두 점과 견주는데, 두 점은 띠가 아니다.",
    "죽는조건  네 점이 모두 78~82 에 모이면 참고선을 «80 언저리» 로 적을 수 있다.",
    "        흩어지면 이 참고선 자체를 접고, 사다리를 참고선 없이 읽는다.",
    "⛔안답함  ⛔이것은 **널이 아니다**(한계 ③). 확률적 반복이 아니라 다른 결정적 격자다.",
    "⛔안답함  ⛔예산은 경로당 가중치도 함께 바꾼다(한계 ④) — 단일 변수가 아니다.",
    "⛔⛔안답함  **이 축은 한쪽으로만 열려 있다.** 광선 수는 32 비트 천장",
    "        4,294,967,295 를 못 넘는다(Sionna 표본기 wavefront_size 가 uint32 ·",
    "        elevation_sweep_md.py 가 dry-run 에서 막는다. 4.4e9 로 짜 봤다가 걸렸다).",
    "        규약값 4e9 는 그 천장의 93 % 라 **위로는 7 % 밖에 못 간다.**",
    "        ⇒ 3.6/3.8/4.0/4.2/4.29 는 아래로 치우친 다섯 점이다. 대칭 띠가 아니다.")
#: ⛔4.29e9 는 천장(4,294,967,295) 바로 아래다 — 더 올리면 하네스가 막는다
for spp in (3_600_000_000, 4_290_000_000):
    job(el=-60, spp=spp)

GROUPS.append(("끝", len(OUT)))
if "--summary" in sys.argv:
    n = sum(1 for x in OUT if x and not x.startswith("#"))
    print(f"발주 줄 {n} (샤드 나눔 포함) · 어림 {_cost / 60:.1f} 일꾼시간")
    for (t1, i1), (_t2, i2) in zip(GROUPS, GROUPS[1:]):
        c = sum(1 for x in OUT[i1:i2] if x and not x.startswith("#"))
        print(f"  {c:>3} 줄  {t1[:74]}")
    print("\n⚠어림은 0923 발주서의 «빈 하늘 44 분 · 우리 씬 136 분» 을 그대로 쓴 것이다.")
    print("  땅만 있는 씬이 «통째» 보다 쌀 수 있으므로 **위쪽 어림**이다.")
else:
    print("\n".join(OUT))
