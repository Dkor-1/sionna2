#!/usr/bin/env python
"""0925 발주서 — 협곡의 «격자 민감도» 를 두 점에서 **사다리**로 넓힌다.

■ 어디서 나왔나 (⛔지어낸 물음이 아니다)
  2026-09-10 에 `benchmark/read_canyonnull_0910.py` 가 협곡의 광선 예산 ±5 % 를 읽었다
  (원장 `outputs/read_canyonnull_0910.json`). 사건 규칙(DEV=0.5) 기준:
      el −30 : 기준 96 · 3.8e9 에서 79 남음(자카드 0.6031) · 4.2e9 에서 80 남음(0.6250)
      el −60 : 기준 128 · 3.8e9 에서 109 남음(0.7315) · 4.2e9 에서 113 남음(0.7740)
  그리고 그 판독기가 스스로 못 박았다 — **「두 점은 신뢰구간이 아니다」**(:186).
  2026-09-11 재검토에서 그 두 점을 「0.60~0.77 띠」로 합쳐 **다른 기체의 판정 문턱**으로 쓰던
  문장을 내렸다(work/sweep_0904/RESUME_0911.md · runners/make_jobs_0923.py C 묶음).

  ⇒ 그러면 **남는 물음은 하나**다: 두 점을 금지어로만 둘 게 아니라,
    **한 앙각 안에서 예산을 더 사서 «민감도가 예산 변화에 어떻게 움직이나»를 본다.**
  ⚠같은 날 조사에서 남이 이 현상을 수치화한 게재판을 찾았다(arXiv 2609.11121, IEEE GLOBECOM
    2026) — Sionna RT 의 겉보기 편향 가운데 약 70 %가 광선 부족이고 예산을 늘리면 준다고 잰다.
    ⛔주파수대(28~300 GHz)와 잣대(공간 SNR 분포)가 우리와 달라 **그 수를 옮겨 쓰지 않는다.**
    우리는 우리 잣대(사건 목록 겹침)로 우리 대역에서 잰다.

■ 무엇을 사나 — 협곡 · matrice4e · 15 m · 팔 R0D0E0F1 · 깊이 2 · 자세 8,192
  이미 있는 점: 3.8e9(−5 %) · 4.0e9(기준) · 4.2e9(+5 %)
  새로 사는 점: **3.6e9(−10 %) · 3.9e9(−2.5 %) · 4.1e9(+2.5 %) · 4.29e9(+7.25 %)**
  두 앙각(−30 · −60) × 네 점 × 샤드 2 = **32 줄** (장면 16 + 빈 하늘 16)

  ⛔⛔**이 축은 위로 비대칭이다 — 천장이 있다.** 처음에 +10 %(4.4e9)로 잡았더니
    `elevation_sweep_md.py:567` 의 가드가 막았다: Sionna 표본기의 `wavefront_size` 가 uint32 라
    **4,294,967,295 을 넘는 줄은 절대 안 돈다.** 규약값 4e9 가 그 바로 아래다.
    ⇒ 위쪽 끝은 **4.29e9(+7.25 %)** 가 한계다. −10 % 는 되고 +10 % 는 안 된다.
    ⚠결과를 읽을 때 이 비대칭을 함께 적는다 — 「위로 덜 갔다」가 잣대 탓인지 물리 탓인지
      이 축으로는 못 가른다.

■ ⛔이 묶음이 **답하지 않는** 것
  · ⛔**여전히 «널» 이 아니다.** 초기 광선은 씨앗 없는 결정적 피보나치 격자다
    (sionna/rt/utils/ray_tracing.py:24-30) — 예산을 바꾸는 것은 **격자를 다시 써는** 일이고
    확률 표본을 뽑는 일이 아니다. 점이 일곱이 되어도 신뢰구간이 되지 않는다.
  · ⛔광선 수를 바꾸면 경로 수와 **경로당 가중치**가 함께 움직인다(field_calculator.py:221).
    단일 변수가 아니다. ⛔「솔버의 결함」으로도 「상쇄되니 괜찮다」로도 읽지 않는다.
  · ⛔이것으로 **다른 기체**(mini5pro)의 자세 집합을 견줄 수 있게 되지 않는다 — 회전수가 달라
    같은 자세 번호가 다른 각이다(make_jobs_0923.py C 묶음이 이미 그렇게 적었다).
  · ⛔실기 계측 대조는 0 건이고 이 판으로도 안 생긴다.

■ 죽는조건 (⇒ 무엇을 보면 이 축을 접나)
  · 겹침이 예산 변화량과 **단조**로 움직이면 「민감도는 격자 간격을 따라간다」가 서고, 그때
    비로소 **한 앙각 안에서** 폭을 적을 수 있다.
  · 겹침이 예산과 **무관하게 흩어지면**(예: −2.5 % 가 −10 % 보다 더 갈리면) 이 잣대는 예산으로
    통제되지 않는다는 뜻이다 ⇒ **자카드를 손잡이 비교의 잣대로 쓰는 것을 그만둔다.**
  · 어느 칸이든 경로 수가 상한(2,000,000)에 붙으면 그 칸은 접는다(집 규약).

쓰는 법:
    /workspace/.venvs/py312/bin/python runners/make_jobs_0925.py --summary
    /workspace/.venvs/py312/bin/python runners/make_jobs_0925.py > runners/jobs_0925.txt
  ⭐발주 전 반드시:
    grep -vE "^\\s*(#|$)" runners/jobs_0925.txt \\
      | xargs -d"\\n" -P 4 -I{} runners/filter_jobs.sh {} | cut -d"|" -f1 | sort | uniq -c
"""
from __future__ import annotations
import sys

ARM, ENV, NSH = "R0D0E0F1", "sionna:simple_street_canyon", 2
ELS = (-30, -60)
#: 기준 4e9 에 대한 비율 — 이미 산 ±5 % 사이를 메우고 ±10 % 로 넓힌다
#: ⛔위쪽 끝은 uint32 천장(4,294,967,295)이 정한다 — elevation_sweep_md.py:567 이 막는다
SPPS = [(3_600_000_000, "−10 %"), (3_900_000_000, "−2.5 %"),
        (4_100_000_000, "+2.5 %"), (4_290_000_000, "+7.25 % · 천장 바로 아래")]
BASE = "--engine sionna --n-poses 8192 --max-depth 2 --range-m 15"

OUT: list = []
OUT.append("# ══ 0925 큐 — 협곡 격자 민감도를 두 점에서 사다리로 ══")
OUT.append("#  ⛔여기 적힌 것은 «물음» 이지 «답» 이 아니다.")
OUT.append("#  ⛔예산을 바꾸는 것은 «격자를 다시 써는» 일이다 — 점이 일곱이 되어도 널이 아니다.")
OUT.append("#  ⛔이것으로 다른 기체의 자세 집합을 견줄 수 있게 되지 않는다(회전수가 다르다).")
OUT.append("#  ⛔실기 계측 대조는 0 건이고 이 판으로도 안 생긴다.")
OUT.append("#  ⛔축이 위로 비대칭이다 — uint32 천장 4,294,967,295 때문에 +10 % 는 못 산다.")
OUT.append("#     위쪽 끝은 4.29e9(+7.25 %)가 한계다. 결과에 이 비대칭을 함께 적는다.")
OUT.append("#  ⚠한 샤드가 실측 중앙 238 분이다 — 32 줄이면 어림 64 일꾼시간.")
OUT.append("")
for el in ELS:
    OUT.append(f"# ── 앙각 {el:+d} — 이미 있는 점 3.8e9 · 4.0e9 · 4.2e9 사이와 바깥")
    for spp, lbl in SPPS:
        OUT.append(f"#   예산 {spp:,} ({lbl})")
        for k in range(NSH):
            #: ⭐⭐**장면과 빈 하늘을 같은 예산으로 짝지어 산다.**
            #  ⛔read_canyonnull_0910.stem() 이 둘을 같은 예산으로 묶는다 — 장면만 사면
            #    그 예산 점은 **한 칸도 못 읽는다**(2026-09-11 실측: 새 점의 빈 하늘 0 장).
            OUT.append(f"{BASE} --spp {spp} --sw {ARM} --els={el} --env {ENV} "
                       f"--shard {k} --nshards {NSH}")
            OUT.append(f"{BASE} --spp {spp} --sw {ARM} --els={el} "
                       f"--shard {k} --nshards {NSH}")
    OUT.append("")

if "--summary" in sys.argv:
    n = sum(1 for x in OUT if x and not x.startswith("#"))
    print(f"발주 줄 {n} (샤드 나눔 포함) · 앙각 {len(ELS)} × 예산 {len(SPPS)} × 샤드 {NSH}")
    print("어림 — 협곡 한 샤드 238 분 ⇒ 16 × 4.0 h ≈ 64 일꾼시간")
else:
    print("\n".join(OUT))
