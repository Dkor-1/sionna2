from __future__ import annotations

BASE = ("--engine sionna --spp {spp} --n-poses 8192 --max-depth {d} --range-m 15 "
        "--sw {sw}")


def line(sw="R0D0E0F1", el=-30, env=None, spp=4000000000, d=2, fc=None,
         prf=None, alt=None, shard=0):
    s = BASE.format(spp=spp, d=d, sw=sw)
    if fc is not None:
        s += f" --fc-ghz {fc}"
    if prf is not None:
        s += f" --prf {prf}"
    s += f" --els={el:g}"
    if env:
        s += f" --env {env}"
    if alt is not None:
        s += f" --env-alt {alt}"
    return s + f" --shard {shard} --nshards 2"


def both(**kw):
    return [line(shard=0, **kw), line(shard=1, **kw)]


def main() -> None:
    out: list[str] = []

    def block(title, rows):
        out.append("")
        out.append(f"# ── {title}")
        out.extend(rows)

    # A. 조각 장면에 굴절 팔 — 20 줄
    a = []
    for env in ("outdoor01_ground", "outdoor01_bldg"):
        for el in (-75, -60, -45, -30, -15):
            a += both(sw="R1D0E0F1", el=el, env=env)
    block("A 조각 장면에 굴절 팔 (20 줄 · 약 29 h) — 건물만 판이 굴절로 얹기 시작하나", a)

    # B. 실외 고도 사다리 — 14 줄
    b = []
    for el in (-30, -60):
        for alt in (40, 80):
            b += both(el=el, env="outdoor01", alt=alt)
    b += both(el=-30, env="outdoor01_ground", alt=80)
    for alt in (40, 80):
        b += both(el=-60, env="outdoor01_ground", alt=alt)
    block("B 실외 고도 사다리 (14 줄 · 약 28 h) — 바닥이 지면 탓인가", b)

    # C. 실외 대역 팔의 광선 예산 짝 — 10 줄
    c = []
    for fc in (None, 3.45, 3.475, 3.525, 3.55):
        c += both(el=-60, env="outdoor01", spp=3900000000, fc=fc)
    block("C 실외 대역 팔의 광선 예산 짝 (10 줄 · 약 22 h) — 대역 기울기가 광선 흔들림보다 큰가", c)

    # D. 실외 끝점 −90 — 8 줄
    d = []
    for env in ("outdoor01", "outdoor01_ground"):
        for sw in ("R0D0E0F1", "R1D0E0F1"):
            d += both(sw=sw, el=-90, env=env)
    block("D 실외 끝점 앙각 −90 (8 줄 · 약 14 h) — 지면 봉우리가 끝에서도 이어지나", d)

    # E. 위상을 볼 수 있게 촘촘한 반송파 — 20 줄
    e = []
    for fc in (3.495, 3.502, 3.505, 3.51):
        for el in (-30, -60):
            e += both(el=el, fc=fc)
    for fc in (3.502, 3.51):
        e += both(el=-60, env="outdoor01", fc=fc)
    block("E 위상용 촘촘한 반송파 (20 줄 · 약 18 h) — 지연 되감기를 풀어 위상을 본다", e)

    # F. 실외 표집률 사다리 — 12 줄
    f = []
    for prf in (39400, 78800, 157600):
        for el in (-30, -60):
            f += both(el=el, env="outdoor01", prf=prf)
    block("F 실외 표집률 사다리 (12 줄 · 약 27 h) — 움직이는 몫이 잡음인가 날개인가", f)

    # G. 굴절 팔 깊이 1 — 4 줄
    g = []
    for el in (-60, -30):
        g += both(sw="R1D0E0F1", el=el, d=1)
    block("G 굴절 팔 깊이 1 두 칸 (4 줄 · 약 2.4 h) — 깊이 축이 굴절 팔에서도 서나", g)

    hdr = [
        "# 0930 발주서 — ⛔**회절(D)·모서리회절(E) 을 켠 줄이 한 줄도 없다**",
        "#   사용자 지시(2026-09-13): 「회절은 일반 배제하고 작업하고 싶어」",
        "#   쓰는 팔은 R0D0E0F1(확산만) · R1D0E0F1(+굴절) 둘뿐. F(확산)는 규약대로 항상 켬.",
        "#   까닭·«아니다» 규칙·비용 근거는 runners/make_jobs_0930.py 머리말에.",
        "#   ⛔el 0 은 한 줄도 없다(GATES_0902).",
    ]
    body = [x for x in out]
    n = len([x for x in body if x and not x.startswith("#")])
    hdr.append(f"#   줄 {n} · 실측 요율로 약 141 일꾼시간 ⇒ 동시 9 이면 경과 약 16 시간")
    print("\n".join(hdr + body))


