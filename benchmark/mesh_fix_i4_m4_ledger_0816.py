def gate(path):
    """mesh_check / adv 로그에서 «결과: N/M 통과» 와 실패 기체를 뽑는다."""
    if not os.path.exists(path):
        return {"로그없음": path}
    t = open(path, encoding="utf-8", errors="replace").read()
    m = re.search(r"결과: (\d+)/(\d+) 통과", t)
    bad = re.findall(r"\[(\w+)\]\s+❌", t)
